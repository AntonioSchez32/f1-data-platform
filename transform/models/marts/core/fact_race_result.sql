{#- Resultados de carrera y de carrera sprint (columna session_type), como en el TFG. -#}
select
    race_id,
    case session_type when 'RACE_RESULT' then 'RACE' else 'SPRINT' end as session_type,
    position_display_order,
    position_number,
    position_text,
    driver_number,
    driver_id,
    constructor_id,
    engine_manufacturer_id,
    tyre_manufacturer_id,
    race_shared_car as is_shared_car,
    race_laps as laps,
    race_time_millis as time_ms,
    race_time_penalty_millis as time_penalty_ms,
    race_gap_millis as gap_ms,
    race_gap_laps as gap_laps,
    race_interval_millis as interval_ms,
    race_reason_retired as reason_retired,
    coalesce(race_points, 0) as points,
    race_grid_position_number as grid_position,
    race_grid_position_text as grid_position_text,
    race_positions_gained as positions_gained,
    race_pit_stops as pit_stops,
    coalesce(race_pole_position, false) as is_pole_position,
    coalesce(race_fastest_lap, false) as is_fastest_lap,
    coalesce(race_driver_of_the_day, false) as is_driver_of_the_day,
    coalesce(race_grand_slam, false) as is_grand_slam,
    coalesce(position_number = 1, false) as is_win,
    coalesce(position_number <= 3, false) as is_podium,
    is_corrected,
    overridden_columns,
    disputed_columns
from {{ ref('int_race_data_corrected') }}
where session_type in ('RACE_RESULT', 'SPRINT_RACE_RESULT')
